// Usage: npm run build && npx vite preview --port 4173 &   then   node scripts/perf-probe.mjs [--report docs/PERF.md]
// Measures draw calls, triangles, frame times and heap of the live scene per quality tier and viewport.
// Every figure belongs to the browser/GPU that produced it; the header records which.
import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';

const reportPath = process.argv.includes('--report')
  ? process.argv[process.argv.indexOf('--report') + 1]
  : '';
const base = process.env.PROBE_URL ?? 'http://127.0.0.1:4173';
const showcase = readFileSync(new URL('./showcase-ages.js', import.meta.url), 'utf8');
const SAMPLE_MS = Number(process.env.SAMPLE_MS ?? 6000);

const browser = await chromium.launch({
  args: [
    '--use-gl=angle',
    '--use-angle=swiftshader',
    '--enable-unsafe-swiftshader',
    '--ignore-gpu-blocklist',
  ],
});
const version = browser.version();
const rows = [];
for (const [vpName, vp, dpr, touch] of [
  ['desktop 1366×768', { width: 1366, height: 768 }, 1, false],
  ['iPhone 390×844 @2x', { width: 390, height: 844 }, 2, true],
]) {
  for (const tier of ['low', 'medium', 'high']) {
    const ctx = await browser.newContext({
      viewport: vp,
      deviceScaleFactor: dpr,
      hasTouch: touch,
      isMobile: touch,
    });
    const page = await ctx.newPage();
    await page.goto(`${base}/?debug&quality=${tier}`, { waitUntil: 'load' });
    await page.waitForFunction(() => !!window.__epoch, null, { timeout: 20000 });
    await page.evaluate(showcase);
    await page.waitForTimeout(3000); // shader compilation and first frames are excluded
    await page.evaluate(() => window.__epoch.perf.reset());
    await page.waitForTimeout(SAMPLE_MS);
    const stats = await page.evaluate(() => window.__epoch.perf.stats());
    rows.push({ viewport: vpName, tier, ...stats });
    console.log(vpName, tier, JSON.stringify(stats));
    await ctx.close();
  }
}
await browser.close();

if (reportPath) {
  const date = new Date().toISOString().slice(0, 10);
  const md = `# Performance record (generated)

Generated by \`node scripts/perf-probe.mjs\` on ${date}. Browser: **Chromium ${version} with SwiftShader (CPU software rasteriser)**, headless, in a cloud
container. **These frame rates say nothing about a real GPU, an iPhone or Safari** — a CPU rasteriser is orders of magnitude slower than any phone GPU. What *is* meaningful here is the
scene's own cost: draw calls, triangles, geometries/textures/programs and JS heap, which do not depend on the rasteriser, and the *relative* cost of the quality tiers.

Scene: the Age showcase village (16 building kinds, citizens, roads, foliage), camera at the default distance, ${SAMPLE_MS / 1000} s of continuous rendering after a 3 s warm-up.

| Viewport | Tier | Frames | FPS (software) | p50 ms | p95 ms | Draw calls | Triangles | Geometries | Textures | Programs | Pixel ratio | JS heap MB |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows
  .map(
    (r) =>
      `| ${r.viewport} | ${r.tier} | ${r.frames} | ${r.fps} | ${r.p50Ms} | ${r.p95Ms} | ${r.drawCalls} | ${r.triangles} | ${r.geometries} | ${r.textures} | ${r.programs} | ${r.pixelRatio} | ${r.heapMB ?? '—'} |`,
  )
  .join('\n')}

## What is and is not claimed

- Targets (60 fps on a midrange laptop, 30 fps on a midrange iPhone) are **unproven**: no real-device measurement exists. The adaptive
  governor (\`src/render/governor.ts\`, unit-tested) is the mitigation: it lowers the pixel ratio first, then sheds post-processing and
  finally the birds and the decorative valley beyond the board. It never removes geometry the player needs or any forecast information.
- Draw-call and triangle counts are real counts from \`renderer.info\` for one whole frame, including the shadow pass and, on the high tier,
  every post-processing pass.
- For comparison, before session 4's visual overhaul the same scene cost 118 draw calls and 344k / 440k / 549k triangles (low / medium /
  high). The overhaul cut draw calls (one instanced smoke system instead of per-chimney meshes) and added triangles, mostly the
  smooth-shaded trees and the valley beyond the board; the latter uses far-detail trees (56–160 triangles instead of 240–344).
- Session 5 gave the villagers headwear and a tool by job (seven instanced meshes of at most 40 each in place of one): 5 more draw calls and about 6k
  more triangles than the session-4 record (81 / 84 draw calls). Hats and tools skip the shadow pass, where they would be invisible.
`;
  writeFileSync(reportPath, md);
  console.log('wrote', reportPath);
}
