/** Generates docs/generated/CONTENT_TABLES.md from the live content data so docs never drift from code. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { BUILDINGS, TECHS, TRADITIONS, GREENVALE, TICKS_PER_SECOND } from '../src/engine';

const cost = (c: Partial<Record<string, number>>) =>
  Object.entries(c)
    .filter(([, v]) => v)
    .map(([k, v]) => `${v} ${k}`)
    .join(', ') || '—';

const lines: string[] = [];
lines.push('# Content tables (generated)\n');
lines.push('> Generated by `npx vite-node scripts/gen-content-tables.ts`. Do not edit by hand.\n');
lines.push('## Buildings\n');
lines.push(
  'Rates are per second at full staffing (internal: milli-units per tick × 10). Resist = permille/10 = %.\n',
);
lines.push(
  '| Building | Enabled | Age | Tech | Footprint | Cost | Build work (builder-s) | Workers | Output/s | Housing | Fire / Flood / Quake resist | Fuel | Heritage |',
);
lines.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|');
for (const d of Object.values(BUILDINGS)) {
  lines.push(
    `| ${d.name} | ${d.enabled ? 'yes' : 'no'} | ${d.age} | ${d.tech ?? '—'} | ${d.w}×${d.h}${d.rotatable ? ' (rot)' : ''} | ${cost(d.cost)} | ${(d.buildWork / TICKS_PER_SECOND).toFixed(1)} | ${d.workers} | ${d.job ? `${((d.output * TICKS_PER_SECOND) / 1000).toFixed(2)} ${d.job}` : '—'} | ${d.housing || '—'} | ${d.resist.fire / 10}% / ${d.resist.flood / 10}% / ${d.resist.quake / 10}% | ${d.fuel} | ${d.heritage ? 'yes' : '—'} |`,
  );
}
lines.push('\n## Technologies\n');
lines.push('| Tech | Branch | Enabled | Knowledge | Research time | Requires | Effect |');
lines.push('|---|---|---|---|---|---|---|');
for (const t of Object.values(TECHS)) {
  lines.push(
    `| ${t.name} | ${t.branch} | ${t.enabled ? 'yes' : 'no'} | ${t.cost} | ${(t.ticks / TICKS_PER_SECOND).toFixed(1)} s | ${t.requires.join(', ') || '—'} | ${t.unlocks} |`,
  );
}
lines.push('\n## Traditions\n');
lines.push('| Tradition | After | Upside | Downside |');
lines.push('|---|---|---|---|');
for (const t of Object.values(TRADITIONS))
  lines.push(`| ${t.name} | ${t.after ?? 'any'} | ${t.upside} | ${t.downside} |`);
lines.push(`\n## Scenario: ${GREENVALE.name}\n`);
lines.push(
  `*${GREENVALE.tagline}* Victory: ≥${GREENVALE.victory.minSurvivors} survivors, ≥${GREENVALE.victory.minHeritage} cross-era heritage structure standing, ≥${GREENVALE.victory.minRetainedTechs} technologies retained after the final collapse.\n`,
);
lines.push(
  '| # | Epoch | Age | Hazard | Strength | Scarcity | Start (food/timber/stone) | Start pop | Years after |',
);
lines.push('|---|---|---|---|---|---|---|---|---|');
for (const e of GREENVALE.epochs) {
  lines.push(
    `| ${e.index + 1} | ${e.name} | ${e.ageName} | ${e.hazard.headline} (${e.hazard.kind}) | ${e.hazard.strength} | ${e.scarcity} | ${e.start.food}/${e.start.timber}/${e.start.stone} | ${e.startPop} | ${e.yearsAfter} |`,
  );
}
mkdirSync('docs/generated', { recursive: true });
writeFileSync('docs/generated/CONTENT_TABLES.md', lines.join('\n') + '\n');
console.log('wrote docs/generated/CONTENT_TABLES.md');
