/**
 * Plays the scripted Greenvale policies on the canonical seed and writes their replayable transcripts and a
 * human-readable report. Run after any rules or content change:  npx vite-node scripts/record-traces.ts
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { BUILDINGS, computeHash, createCampaign, replayCampaign, transcriptOf } from '../src/engine';
import { noopPolicy, playCampaign, type Policy } from '../src/engine/ai/bots';
import { ROUTES } from '../src/engine/ai/routes';

const SEED = 6001;
const dir = 'fixtures/greenvale';
mkdirSync(dir, { recursive: true });

const policies: Policy[] = [ROUTES.engineers!, ROUTES.archivists!, ROUTES.builder!, noopPolicy];
const rows: string[] = [];
const sections: string[] = [];
for (const p of policies) {
  const c = createCampaign(SEED);
  const run = playCampaign(c, p);
  const t = transcriptOf(c);
  const again = replayCampaign(t);
  if (computeHash(again) !== t.finalHash) throw new Error(`${p.name}: replay diverged from the live run`);
  writeFileSync(`${dir}/${p.name}.json`, JSON.stringify(t) + '\n');
  const v = c.report?.verdict;
  const cond = v ? v.conditions.map((x) => `${x.have}/${x.need}`).join(' · ') : '—';
  rows.push(
    `| ${p.name} | ${c.phase} | ${run.epochs.map((e) => e.survivors).join(' → ')} | ${cond} | ${t.actions.length} | \`${t.finalHash}\` |`,
  );
  const lines = [`### ${p.name} — ${c.phase}`, ''];
  for (const e of run.epochs) {
    const kinds = Object.entries(e.built)
      .map(([k, n]) => `${BUILDINGS[k as keyof typeof BUILDINGS].name}×${n}`)
      .join(', ');
    lines.push(
      `- **Epoch ${e.epoch + 1} (${e.hazard})**: ${e.survivors} survivors, ${e.deaths} deaths. Techs: ${e.techs.join(', ') || 'none'}. Decisions: ${e.stories.join(', ') || 'none'}. Standing after: ${kinds}.`,
    );
  }
  if (v) lines.push(`- **Verdict:** ${v.title} — ${v.reason}`);
  sections.push(lines.join('\n'));
}

const md = `# Greenvale route fixtures — EXECUTED

Generated by \`npx vite-node scripts/record-traces.ts\` from the scripted policies in \`src/engine/ai/routes.ts\`
(seed ${SEED}, rules/content ${createCampaign(SEED).rules}/${createCampaign(SEED).content}). Each transcript in
\`fixtures/greenvale/\` is replayed by \`tests/engine/routes.test.ts\`; a changed rules or content file that alters
any outcome fails that test until the traces are re-recorded **and re-read**.

The policies are written with a veteran's foresight of the scenario (which hazard each age brings) — they use the
same forecast and placement information a returning player has, and no hidden engine state.

| Policy | Result | Survivors per epoch | Victory conditions (people · landmarks · techs) | Actions | Final hash |
| --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

## What the two winning routes do differently

**Route A — Engineers (hold the line).** Never leaves the ancestral valley floor. Founds the Archive on the
north-east ridge — inside the future quake zone — and survives by *engineering*: Masonry and Writing in the Age of
Thatch, **Seismic Engineering** in the Age of Bronze, then Retaining Walls, Stone Houses and reinforced stonework
before the Great Quake. It answers story decisions defensively (clear the brush, sandbag, brace the landmark).
Without Seismic Engineering the same policy loses (ablation test).

**Route B — Archivists (scatter and relocate).** Puts its Archive and Seed Vault on ground no hazard of any age
reaches, founds each later society on the High Ground, researches Writing → Masonry → Hydrology → Seismic
Engineering, builds a second Archive, and digs up what was left behind. It answers story decisions by gathering
(timber, harvest) and learning (funding the historian, welcoming refugees). It ends with three standing landmarks and
four retained technologies. Without research, or without an Archive, the same policy loses (ablation test).

## Losing paths

${sections.slice(2).join('\n\n')}

## Full per-epoch accounts

${sections.slice(0, 2).join('\n\n')}
`;
writeFileSync('fixtures/greenvale-traces.md', md);
console.log(rows.join('\n'));
