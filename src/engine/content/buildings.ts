export const BUILDING_KINDS = Object.keys(BUILDINGS) as BuildingKind[];

export function getDef(kind: BuildingKind): BuildingDef {
  return BUILDINGS[kind];
}

/** Cost in fixed-point units. */
export function costOf(kind: BuildingKind): Record<ResourceKey, number> {
  const c = BUILDINGS[kind].cost;
  return {
    food: (c.food ?? 0) * UNIT,
    timber: (c.timber ?? 0) * UNIT,
    stone: (c.stone ?? 0) * UNIT,
    knowledge: (c.knowledge ?? 0) * UNIT,
  };
}

/** Footprint after optional rotation. */
export function footprint(kind: BuildingKind, rot: 0 | 1): { w: number; h: number } {
  const d = BUILDINGS[kind];
  return rot === 1 && d.rotatable ? { w: d.h, h: d.w } : { w: d.w, h: d.h };
}
