import { UNIT } from '../core/constants';
import type { BuildingKind, HazardKind, Material, ResourceKey, TechId } from '../core/types';

/**
 * Building schema. Units:
 *  - cost: whole resource units (multiplied by UNIT at payment)
 *  - buildWork: builder-ticks (1 builder for 1 tick = 1). Stored progress is milli builder-ticks.
 *  - output/upkeep: milli-units per tick at full staffing (10 ticks = 1 s)
 *  - resist/fuel: permille / 0..100
 *  - slopeMax / heights: 1/100 cell
 */
export interface BuildingDef {
  kind: BuildingKind;
  name: string;
  blurb: string;
  /** Catalog hides defs where enabled === false (prototype). */
  enabled: boolean;
  w: number;
  h: number;
  rotatable: boolean;
  /** Minimum epoch index (age) in which this can be built. */
  age: number;
  tech: TechId | null;
  cost: Partial<Record<ResourceKey, number>>;
  buildWork: number;
  maxBuilders: number;
  workers: number;
  job: ResourceKey | null;
  output: number;
  upkeep: Partial<Record<ResourceKey, number>>;
  housing: number;
  slopeMax: number;
  water: 'forbid' | 'require';
  needsRock: boolean;
  needsForest: boolean;
  material: Material;
  resist: Record<HazardKind, number>;
  /** Flammability contribution to the fire map (0..100). */
  fuel: number;
  /**
   * A landmark: counts toward the victory's "landmarks from an earlier age" (and the heritage score). The Archive is
   * not one — it carries knowledge, which the victory counts separately, so one building cannot answer both.
   */
  heritage: boolean;
  limit: number | null;
  /** How many technologies this structure can carry through a collapse. */
  retains: number;
  /** Permille of cost refunded on cancel (only while unfinished). */
  refund: number;
  /** Permille of cost recoverable as salvage from rubble. */
  salvage: number;
  /** Integrity permille lost per century of interregnum. */
  decay: number;
  /** Preplaced by the scenario; not buildable. */
  founder?: boolean;
}

